#!/usr/bin/env python3
"""Fetch Material Symbols (Outlined, Apache 2.0) and write them as vector
drawables into app/src/main/res/drawable/.

    python3 android/scripts/gen_icons.py          # (re)generate every icon below

Add an icon: append (drawable name, symbol name, mirror in RTL) to ICONS and
run the script. Browse names at https://fonts.google.com/icons.
"""

from __future__ import annotations

import re
import urllib.request
from pathlib import Path

ICONS = [
    ("ic_add", "add", False),
    ("ic_close", "close", False),
    ("ic_delete", "delete", False),
    ("ic_expand_more", "expand_more", False),
    ("ic_expand_less", "expand_less", False),
    ("ic_explore", "explore", False),
    ("ic_fit_screen", "fit_screen", False),
    ("ic_globe", "public", False),
    ("ic_help", "help", False),
    ("ic_info", "info", False),
    ("ic_more_vert", "more_vert", False),
    ("ic_my_location", "my_location", False),
    ("ic_radio", "radio", False),
    ("ic_refresh", "refresh", False),
    ("ic_remove", "remove", False),
    ("ic_search", "search", False),
    ("ic_settings", "settings", False),
    ("ic_swap_vert", "swap_vert", False),
    ("ic_bolt", "bolt", False),
    ("ic_cell_tower", "cell_tower", False),
    ("ic_settings_input_antenna", "settings_input_antenna", False),
    ("ic_travel_explore", "travel_explore", False),
    ("ic_fullscreen", "fullscreen", False),
    ("ic_fullscreen_exit", "fullscreen_exit", False),
    ("ic_navigation", "navigation", False),
]

URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/{}/default/24px.svg"
OUT = Path(__file__).resolve().parents[1] / "app" / "src" / "main" / "res" / "drawable"
# Lint flags paths longer than this (VectorPath); these icons are tiny anyway.
LONG_PATH = 800

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols "{symbol}" (Apache 2.0). Generated by android/scripts/gen_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"{tools_ns}
    android:width="24dp"
    android:height="24dp"{mirror}
    android:tint="?android:attr/colorControlNormal"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/white"
            android:pathData="{d}"{ignore} />
    </group>
</vector>
"""


def main() -> None:
    for name, symbol, mirror in ICONS:
        svg = urllib.request.urlopen(URL.format(symbol), timeout=30).read().decode()
        if 'viewBox="0 -960 960 960"' not in svg:
            raise SystemExit(f"{symbol}: unexpected viewBox")
        paths = re.findall(r'<path d="([^"]+)"', svg)
        if len(paths) != 1:
            raise SystemExit(f"{symbol}: expected one path, got {len(paths)}")
        d = paths[0]
        long = len(d) > LONG_PATH
        (OUT / f"{name}.xml").write_text(
            TEMPLATE.format(
                symbol=symbol,
                d=d,
                mirror='\n    android:autoMirrored="true"' if mirror else "",
                tools_ns='\n    xmlns:tools="http://schemas.android.com/tools"' if long else "",
                ignore='\n            tools:ignore="VectorPath"' if long else "",
            )
        )
        print(f"{name}.xml  ({symbol}, {len(d)} chars)")


if __name__ == "__main__":
    main()
