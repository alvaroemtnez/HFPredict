#!/usr/bin/env python3
"""Turns the shared string tables (i18n/<lang>.json) into Android string
resources, and checks the tables against each other.

The GNOME app reads the JSON directly; Android needs XML. Both apps use the
same keys and the same `{name}` placeholders, so a sentence reads the same on
a phone and a desktop.

Usage: tools/gen-strings.py           write android/app/src/main/res/values*/strings.xml
       tools/gen-strings.py --check   only report missing keys and placeholder mismatches
"""
import json
import os
import re
import sys

LANGS = ["en", "es", "ca", "de", "ja", "ar"]
RES = "android/app/src/main/res"
PLACEHOLDER = re.compile(r"\{([a-zA-Z]+)\}")


def load(lang):
    with open(f"i18n/{lang}.json") as f:
        return json.load(f)


def escape(text):
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def name(key):
    return key.replace(".", "_")


def main():
    check_only = "--check" in sys.argv
    english = load("en")
    problems = 0
    for lang in LANGS:
        table = load(lang)
        missing = [k for k in english if k not in table and k != "app.name"]
        extra = [k for k in table if k not in english]
        for k, v in table.items():
            if k in english and set(PLACEHOLDER.findall(v)) != set(PLACEHOLDER.findall(english[k])):
                print(f"{lang}: {k}: placeholders differ from English")
                problems += 1
        if lang != "en" and missing:
            print(f"{lang}: {len(missing)} missing")
        for k in extra:
            print(f"{lang}: unknown key {k}")
            problems += 1
        if check_only:
            continue
        folder = "values" if lang == "en" else f"values-{lang}"
        os.makedirs(f"{RES}/{folder}", exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by tools/gen-strings.py from i18n/%s.json; edit that, not this. -->" % lang,
                 # Some strings only the GNOME app uses; untranslated ones fall
                 # back to English.
                 '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources,MissingTranslation,Typos">']
        for k, v in table.items():
            if k not in english:
                continue
            attrs = ' translatable="false"' if k == "app.name" else ""
            # Placeholders are {named}; a literal % is never a printf format.
            if "%" in v:
                attrs += ' formatted="false"'
            if k == "app.name" and lang != "en":
                continue
            lines.append(f'    <string name="{name(k)}"{attrs}>{escape(v)}</string>')
        lines.append("</resources>")
        with open(f"{RES}/{folder}/strings.xml", "w") as f:
            f.write("\n".join(lines) + "\n")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
